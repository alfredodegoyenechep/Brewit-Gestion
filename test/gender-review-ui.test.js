const test = require('node:test'), assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path');
const XLSX = require('xlsx'), { chromium } = require('playwright-core');
const { setup, fill, IDS } = require('./helpers/gender-review-fixture');
const chrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
test('sidebar review supports filters, export, preview, import, audit history and responsive layout', { skip: !fs.existsSync(chrome) }, async t => {
  const s = await setup(t), browser = await chromium.launch({ executablePath: chrome, headless: true }); t.after(() => browser.close());
  const page = await browser.newPage({ viewport: { width: 1700, height: 1100 } }), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(s.base);
  await page.getByRole('link', { name: 'Caracterización de la Venta', exact: true }).click();
  await page.locator('#demand-filters button[type=submit]').click();
  await page.locator('#demand-status').filter({ hasText: 'Análisis actualizado.' }).waitFor();
  await page.locator('#sales-clusters-open').click();
  await page.locator('#sales-clusters-status').filter({ hasText: 'Selecciona filtros y dimensiones' }).waitFor();
  await page.locator('#sales-clusters-close').click();
  const nav = page.locator('.nav-group').filter({ has: page.getByRole('heading', { name: 'Control y configuración', exact: true }) });
  await nav.getByRole('link', { name: 'Revisión de género de ventas', exact: true }).click();
  const view = page.locator('#gender-review-workspace');
  await view.locator('#gender-review-status').filter({ hasText: '4 registros encontrados' }).waitFor();
  await view.locator('#gender-review-location').selectOption('store-1');
  await view.locator('#gender-review-search').fill('alfredo');
  await view.getByRole('button', { name: 'Consultar', exact: true }).click();
  await view.locator('#gender-review-status').filter({ hasText: '1 registros encontrados' }).waitFor();
  assert.match(await view.locator('tbody#gender-review-body').innerText(), /Alfredo/);
  const pending = page.waitForEvent('download'); await view.getByRole('button', { name: 'Exportar registros filtrados' }).click();
  const file = path.join(s.root, 'review.xlsx'); await (await pending).saveAs(file);
  const book = XLSX.readFile(file); assert.equal(book.Sheets.Asignaciones.C2.t, 's'); assert.equal(book.Sheets.Asignaciones.C2.v, IDS.name);
  fs.writeFileSync(file, fill(book, { [`store-1:${IDS.name}`]: 'Femenino' }));
  assert.equal(await view.locator('#gender-review-reviewer').count(), 0);
  await view.locator('#gender-review-file').setInputFiles(file);
  await view.getByRole('button', { name: 'Revisar archivo', exact: true }).click();
  await view.locator('#gender-review-preview-summary').filter({ hasText: '1 asignación para aplicar' }).waitFor();
  assert.equal(await view.locator('#gender-review-preview table').count(), 0);
  assert.equal(await view.locator('#gender-review-preview-categories .recurrence-kpi').count(), 4);
  assert.equal(await view.locator('#gender-review-preview-categories [data-category=feminine] strong').innerText(), '1');
  assert.equal(await view.locator('#gender-review-preview-categories [data-category=masculine] strong').innerText(), '0');
  assert.equal((await fetch(`${s.base}/api/sales/gender-review?status=reviewed`).then(r => r.json())).total, 0);
  await page.screenshot({ path: '/tmp/brewit-gender-review-summary.png', fullPage: true });
  await view.getByRole('button', { name: 'Cancelar', exact: true }).click();
  assert.equal(await view.locator('#gender-review-preview').isVisible(), false);
  assert.equal((await fetch(`${s.base}/api/sales/gender-review?status=reviewed`).then(r => r.json())).total, 0);
  await view.getByRole('button', { name: 'Revisar archivo', exact: true }).click();
  await view.locator('#gender-review-preview').waitFor();
  await view.getByRole('button', { name: 'Confirmar 1 asignación', exact: true }).click();
  await view.locator('#gender-review-import-status').filter({ hasText: '1 asignaciones guardadas' }).waitFor();
  assert.equal(await page.locator('#demand-report').evaluate(node => node.hidden), true);
  assert.match(await page.locator('#demand-status').textContent(), /asignaciones de género cambiaron/);
  assert.match(await page.locator('#sales-clusters-status').textContent(), /asignaciones de género cambiaron/);
  assert.equal(await page.locator('#sales-clusters-coverage').textContent(), '');
  await view.locator('#gender-review-status').filter({ hasText: '0 registros encontrados' }).waitFor();
  await view.locator('#gender-review-state').selectOption('reviewed'); await view.getByRole('button', { name: 'Consultar', exact: true }).click();
  await view.locator('#gender-review-status').filter({ hasText: '1 registros encontrados' }).waitFor();
  assert.match(await view.locator('#gender-review-body').innerText(), /Femenino.*Revisado/s);
  await view.locator('#gender-review-body summary').click();
  await view.locator('#gender-review-body details').filter({ hasText: 'review.xlsx' }).waitFor();
  for (const width of [390, 768, 1700]) { await page.setViewportSize({ width, height: 1100 }); await page.waitForFunction(() => document.documentElement.scrollWidth <= innerWidth); }
  await page.waitForFunction(() => Math.abs(document.querySelector('.sidebar').getBoundingClientRect().width - 280) < 1);
  await page.screenshot({ path: '/tmp/brewit-gender-review-test.png', fullPage: true });
  assert.deepEqual(errors, []);
});
